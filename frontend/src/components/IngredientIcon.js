const FALLBACK = require('../../assets/icons/sugar.png');

const IngredientIcon = ({ name, size = 52 }) => {
  const lower = name?.toLowerCase() || '';
  let matchedKey = null;

  const sortedKeys = Object.keys(ICONS).sort((a, b) => b.length - a.length);
  for (const key of sortedKeys) {
    if (lower.includes(key)) {
      matchedKey = key;
      break;
    }
  }

  const source = matchedKey ? ICONS[matchedKey] : FALLBACK;

  return (
    <View style={{
      width: size,
      height: size,
      borderRadius: size / 2,
      alignItems: 'center',
      justifyContent: 'center',
    }}>
      <Image source={source} style={{ width: size, height: size }} />
    </View>
  );
};

export default IngredientIcon;
